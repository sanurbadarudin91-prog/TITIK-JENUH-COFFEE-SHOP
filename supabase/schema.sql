-- 4a. Pengunjung membuat pesanan. Harga & modal SELALU diambil dari
--     tabel menu_items, jadi pengunjung tidak bisa memalsukan harga.
create or replace function public.create_order(
  p_name  text,
  p_table text  default '',
  p_note  text  default '',
  p_items jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order_id bigint;
  v_code     text;
  v_total    integer := 0;
  v_item     jsonb;
  v_menu     record;
  v_qty      integer;
begin
  if p_name is null or length(btrim(p_name)) = 0 then
    raise exception 'Nama pemesan wajib diisi.';
  end if;

  if p_items is null
     or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 then
    raise exception 'Pilih minimal 1 menu dulu ya.';
  end if;

  v_code := 'TJC-' || to_char(now(), 'YYMMDD') || '-'
            || lpad(((random() * 9000)::int + 1000)::text, 4, '0');

  insert into public.orders
    (code, customer_name, table_no, note, status, payment_status, total)
  values
    (v_code, left(btrim(p_name), 60), left(coalesce(p_table, ''), 20),
     left(coalesce(p_note, ''), 200), 'pending', 'unpaid', 0)
  returning id into v_order_id;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := greatest(1, least(50, coalesce(nullif(v_item->>'qty', '')::int, 1)));

    select id, name, price, cost into v_menu
      from public.menu_items
     where id = nullif(v_item->>'id', '')::bigint
       and available = true;

    if found then
      insert into public.order_items
        (order_id, menu_id, name, price, cost, qty, subtotal)
      values
        (v_order_id, v_menu.id, v_menu.name, v_menu.price, v_menu.cost,
         v_qty, v_menu.price * v_qty);

      v_total := v_total + (v_menu.price * v_qty);
    end if;
  end loop;

  if v_total = 0 then
    raise exception 'Menu tidak valid.';
  end if;

  update public.orders set total = v_total where id = v_order_id;

  return jsonb_build_object('code', v_code, 'total', v_total, 'status', 'pending');
end;
$$;

-- 4b. Statistik dashboard. Dijaga is_admin() di dalam fungsi.
create or replace function public.admin_stats()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_gross          integer := 0;
  v_approved_count integer := 0;
  v_cogs           integer := 0;
  v_expenses       integer := 0;
  v_paid           integer := 0;
  v_paid_count     integer := 0;
  v_pending        integer := 0;
  v_pending_value  integer := 0;
  v_rejected       integer := 0;
  v_best           jsonb;
  v_last7          jsonb;
begin
  if not public.is_admin() then
    raise exception 'Akses ditolak.';
  end if;

  select coalesce(sum(total), 0), count(*)
    into v_gross, v_approved_count
    from public.orders where status = 'approved';

  select coalesce(sum(oi.cost * oi.qty), 0)
    into v_cogs
    from public.order_items oi
    join public.orders o on o.id = oi.order_id
   where o.status = 'approved';

  select coalesce(sum(amount), 0) into v_expenses from public.expenses;

  select coalesce(sum(total), 0), count(*)
    into v_paid, v_paid_count
    from public.orders
   where status = 'approved' and payment_status = 'paid';

  select count(*), coalesce(sum(total), 0)
    into v_pending, v_pending_value
    from public.orders where status = 'pending';

  select count(*) into v_rejected from public.orders where status = 'rejected';

  select coalesce(
           jsonb_agg(jsonb_build_object('name', name, 'qty', qty) order by qty desc),
           '[]'::jsonb)
    into v_best
    from (
      select oi.name, sum(oi.qty)::int as qty
        from public.order_items oi
        join public.orders o on o.id = oi.order_id
       where o.status = 'approved'
       group by oi.name
       order by sum(oi.qty) desc
       limit 5
    ) t;

  select coalesce(
           jsonb_agg(jsonb_build_object('day', day, 'total', total) order by day),
           '[]'::jsonb)
    into v_last7
    from (
      select to_char(created_at::date, 'YYYY-MM-DD') as day,
             sum(total)::int as total
        from public.orders
       where status = 'approved'
         and created_at >= (now() - interval '6 days')
       group by created_at::date
    ) t;

  return jsonb_build_object(
    'revenue', jsonb_build_object(
      'gross',    v_gross,
      'cogs',     v_cogs,
      'expenses', v_expenses,
      'net',      v_gross - v_cogs - v_expenses
    ),
    'balance', jsonb_build_object(
      'paid',       v_paid,
      'ordersPaid', v_paid_count
    ),
    'orders', jsonb_build_object(
      'approved',     v_approved_count,
      'pending',      v_pending,
      'rejected',     v_rejected,
      'pendingValue', v_pending_value
    ),
    'bestSeller', v_best,
    'last7',      v_last7
  );
end;
$$;

-- 4c. Catat aktivitas admin (dipanggil dari panel admin).
create or replace function public.log_activity(p_action text, p_detail text default '')
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor text;
begin
  if not public.is_admin() then
    raise exception 'Akses ditolak.';
  end if;

  select username into v_actor from public.admins where user_id = auth.uid();
  v_actor := coalesce(v_actor, 'admin');

  insert into public.activity_log (actor, action, detail)
  values (v_actor, left(p_action, 60), left(coalesce(p_detail, ''), 200));
end;
$$;

