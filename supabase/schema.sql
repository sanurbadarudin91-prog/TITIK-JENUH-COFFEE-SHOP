-- 3. ROW LEVEL SECURITY
--
-- Pengunjung hanya boleh melihat menu. Membuat pesanan HANYA lewat
-- RPC create_order(). Seluruh data pesanan & keuangan hanya untuk admin.
-- ------------------------------------------------------------
alter table public.menu_items   enable row level security;
alter table public.orders       enable row level security;
alter table public.order_items  enable row level security;
alter table public.expenses     enable row level security;
alter table public.activity_log enable row level security;
alter table public.admins       enable row level security;

-- menu_items: publik boleh baca menu tersedia; admin akses penuh
drop policy if exists menu_public_read on public.menu_items;
create policy menu_public_read on public.menu_items
  for select to anon, authenticated
  using (available = true);

drop policy if exists menu_admin_read on public.menu_items;
create policy menu_admin_read on public.menu_items
  for select to authenticated
  using (public.is_admin());

drop policy if exists menu_admin_write on public.menu_items;
create policy menu_admin_write on public.menu_items
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- orders: hanya admin
drop policy if exists orders_admin_read on public.orders;
create policy orders_admin_read on public.orders
  for select to authenticated
  using (public.is_admin());

drop policy if exists orders_admin_update on public.orders;
create policy orders_admin_update on public.orders
  for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists orders_admin_delete on public.orders;
create policy orders_admin_delete on public.orders
  for delete to authenticated
  using (public.is_admin());

-- order_items: hanya admin
drop policy if exists items_admin_read on public.order_items;
create policy items_admin_read on public.order_items
  for select to authenticated
  using (public.is_admin());

-- expenses: hanya admin
drop policy if exists expenses_admin_all on public.expenses;
create policy expenses_admin_all on public.expenses
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- activity_log: hanya admin
drop policy if exists log_admin_all on public.activity_log;
create policy log_admin_all on public.activity_log
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- admins: admin boleh melihat barisnya sendiri
drop policy if exists admins_self_read on public.admins;
create policy admins_self_read on public.admins
  for select to authenticated
  using (user_id = auth.uid());

