          (v_id, m.id, m.name, m.price, m.cost, v_qty, m.price * v_qty);

        v_total := v_total + (m.price * v_qty);
      end if;
    end loop;

    update public.orders set total = v_total where id = v_id;
  end loop;
end $$;
