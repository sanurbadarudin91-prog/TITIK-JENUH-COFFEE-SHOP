  ]'::jsonb;
  o       jsonb;
  k       text;
  v_qty   integer;
  v_id    bigint;
  v_total integer;
  m       record;
begin
  if exists (select 1 from public.orders) then return; end if;

  for o in select * from jsonb_array_elements(d) loop
    v_total := 0;

    insert into public.orders
      (code, customer_name, table_no, note, status, payment_status, total)
    values
      ('TJC-DEMO-' || ((random() * 9000)::int + 1000)::text,
       o->>'name', o->>'table', '', o->>'status', o->>'payment', 0)
    returning id into v_id;

    for k in select * from jsonb_object_keys(o->'items') loop
      v_qty := (o->'items'->>k)::int;

      select id, name, price, cost into m
        from public.menu_items where name = k;

      if found then
        insert into public.order_items
          (order_id, menu_id, name, price, cost, qty, subtotal)
