-- ------------------------------------------------------------
-- 1. TABEL
-- ------------------------------------------------------------
create table if not exists public.menu_items (
  id          bigint generated by default as identity primary key,
  name        text    not null,
  category    text    not null,
  description text    not null default '',
  price       integer not null check (price >= 0),
  cost        integer not null default 0 check (cost >= 0),
  available   boolean not null default true,
  sort_order  integer not null default 0,
  created_at  timestamptz not null default now()
);

create table if not exists public.orders (
  id             bigint generated by default as identity primary key,
  code           text    not null unique,
  customer_name  text    not null,
  table_no       text    not null default '',
  note           text    not null default '',
  status         text    not null default 'pending'
                 check (status in ('pending', 'approved', 'rejected')),
  payment_status text    not null default 'unpaid'
                 check (payment_status in ('unpaid', 'paid')),
  total          integer not null default 0,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);

create table if not exists public.order_items (
  id       bigint generated by default as identity primary key,
  order_id bigint  not null references public.orders(id) on delete cascade,
  menu_id  bigint  references public.menu_items(id) on delete set null,
  name     text    not null,
  price    integer not null,
  cost     integer not null default 0,
  qty      integer not null check (qty > 0),
  subtotal integer not null
);

create table if not exists public.expenses (
  id         bigint generated by default as identity primary key,
  label      text    not null,
  amount     integer not null check (amount > 0),
  created_at timestamptz not null default now()
);

create table if not exists public.activity_log (
  id         bigint generated by default as identity primary key,
  actor      text    not null,
  action     text    not null,
  detail     text    not null default '',
  created_at timestamptz not null default now()
);

-- Daftar akun yang boleh mengelola data (selain login Supabase Auth).
create table if not exists public.admins (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  username   text not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_orders_status  on public.orders(status);
create index if not exists idx_orders_created on public.orders(created_at desc);
create index if not exists idx_items_order    on public.order_items(order_id);

-- ------------------------------------------------------------
-- 2. HELPER: siapa yang boleh jadi admin?
-- ------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

