declare
  d       jsonb := '[
    {"name":"Rani",  "table":"A3", "status":"approved", "payment":"paid",   "items":{"Kopi Susu Titik Jenuh":2,"Croissant Butter":1}},
    {"name":"Bagas", "table":"B1", "status":"approved", "payment":"paid",   "items":{"Americano":1,"Kentang Goreng":2}},
